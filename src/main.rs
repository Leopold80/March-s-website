mod server;  // 服务器配置模块
mod pages;   // 页面处理模块

/// 程序主入口
/// 
/// #[tokio::main] 说明：
/// - tokio 是 Rust 的异步运行时
/// - Web 服务器必须用异步，因为要同时处理多个用户请求
#[tokio::main]
async fn main() {
    server::start().await;  // 启动服务器，一直运行直到关闭
}
